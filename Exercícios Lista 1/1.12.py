
# alocação de memória

raio = 0

circun = 0

area = 0

# entrada de dados

raio = float(input("Informe o raio do círculo: \n"))

# processamento de dados

circun = 2*3,14*raio
area = 3,14*(raio**2)

# saida de dados

print(f"A circunferência do círculo de raio {raio} é igual a {circun}, e sua área é igual a {area}")